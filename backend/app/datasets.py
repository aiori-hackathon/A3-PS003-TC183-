"""Traffic dataset registry, loading, chronological splitting and windowing.

Datasets are arrays of shape (T, N, F): time steps x sensors x features.
"""

from __future__ import annotations

import hashlib
import threading
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np

from .config import DATA_DIR


@dataclass
class DatasetSpec:
    id: str
    name: str
    source: str
    description: str
    filename: str | None
    interval_minutes: int
    start_time: datetime
    features: list[str]
    units: dict[str, str]
    is_synthetic: bool = False
    references: list[str] = field(default_factory=list)


@dataclass
class TrafficDataset:
    spec: DatasetSpec
    values: np.ndarray  # (T, N, F) float32
    sha256: str

    @property
    def num_steps(self) -> int:
        return int(self.values.shape[0])

    @property
    def num_sensors(self) -> int:
        return int(self.values.shape[1])

    def feature_index(self, name: str) -> int:
        return self.spec.features.index(name)

    def timestamp(self, step: int) -> datetime:
        return self.spec.start_time + timedelta(minutes=self.spec.interval_minutes * int(step))


