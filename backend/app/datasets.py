_cache: dict[str, TrafficDataset] = {}
_lock = threading.Lock()


def dataset_path(spec: DatasetSpec) -> Path | None:
    return DATA_DIR / spec.filename if spec.filename else None


def availability(spec: DatasetSpec) -> tuple[bool, str | None]:
    if spec.is_synthetic:
        return True, None
    path = dataset_path(spec)
    if path is None or not path.exists():
        return False, f"File not found: place {spec.filename} in {DATA_DIR}"
    if spec.id == "metr-la":
        try:
            import tables  # noqa: F401
        except ImportError:
            return False, "Reading metr-la.h5 needs the 'tables' package (pip install tables)"
    return True, None


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _generate_synthetic(spec: DatasetSpec) -> np.ndarray:
    rng = np.random.default_rng(2024)
    steps_per_day = 24 * 60 // spec.interval_minutes
    T, N = steps_per_day * 7 * 8, 40
    t = np.arange(T)
    hour = (t % steps_per_day) / steps_per_day * 24
    dow = (t // steps_per_day) % 7
    weekend = (dow >= 5).astype(np.float32)

    flows = np.zeros((T, N), dtype=np.float32)
    for s in range(N):
        base = rng.uniform(80, 400)
        am, pm = rng.uniform(0.2, 1.0), rng.uniform(0.2, 1.0)
        am_t, pm_t = rng.normal(8.0, 0.6), rng.normal(17.5, 0.6)
        daily = (
            0.25
            + am * np.exp(-((hour - am_t) ** 2) / 2.0)
            + pm * np.exp(-((hour - pm_t) ** 2) / 2.5)
            + 0.35 * np.exp(-((hour - 13) ** 2) / 8.0)
        )
        weekly = 1.0 - weekend * rng.uniform(0.2, 0.5)
        noise = rng.normal(0, 0.06, T)
        flows[:, s] = np.clip(base * daily * weekly * (1 + noise), 0, None)
    capacity = flows.max(axis=0, keepdims=True) * 1.15
    speed = 65 * (1 - 0.6 * (flows / capacity) ** 2) + rng.normal(0, 1.5, (T, N))
    return np.stack([flows, speed.astype(np.float32)], axis=-1).astype(np.float32)


def load_dataset(dataset_id: str) -> TrafficDataset:
    if dataset_id not in SPECS:
        raise KeyError(f"Unknown dataset '{dataset_id}'")
    with _lock:
        if dataset_id in _cache:
            return _cache[dataset_id]
        spec = SPECS[dataset_id]
        ok, reason = availability(spec)
        if not ok:
            raise FileNotFoundError(reason)

        if spec.is_synthetic:
            values = _generate_synthetic(spec)
            digest = hashlib.sha256(values.tobytes()).hexdigest()
        elif spec.id == "pems04":
            path = dataset_path(spec)
            with np.load(path, allow_pickle=False) as npz:
                values = np.asarray(npz["data"], dtype=np.float32)
            if values.ndim != 3 or values.shape[2] != 3:
                raise ValueError(f"Unexpected PeMS04 array shape {values.shape}")
            digest = _sha256(path)
        elif spec.id == "metr-la":
            import pandas as pd

            path = dataset_path(spec)
            df = pd.read_hdf(path)
            values = df.to_numpy(dtype=np.float32)[:, :, None]
            spec.start_time = df.index[0].to_pydatetime()
            digest = _sha256(path)
        else:  # pragma: no cover
            raise KeyError(dataset_id)

        values = np.nan_to_num(values, nan=0.0, posinf=0.0, neginf=0.0)
        ds = TrafficDataset(spec=spec, values=values, sha256=digest)
        _cache[dataset_id] = ds
        return ds


def list_datasets() -> list[dict]:
    out = []
    for spec in SPECS.values():
        ok, reason = availability(spec)
        item = {
            "id": spec.id,
            "name": spec.name,
            "source": spec.source,
            "description": spec.description,
            "interval_minutes": spec.interval_minutes,
            "features": spec.features,
            "units": spec.units,
            "is_synthetic": spec.is_synthetic,
            "available": ok,
            "unavailable_reason": reason,
            "references": spec.references,
        }
        if ok:
            ds = load_dataset(spec.id)
            item.update(
                num_steps=ds.num_steps,
                num_sensors=ds.num_sensors,
                start_time=ds.timestamp(0).isoformat(),
                end_time=ds.timestamp(ds.num_steps - 1).isoformat(),
                sha256=ds.sha256,
            )
        out.append(item)
    return out


# --------------------------------------------------------------------------- splitting


@dataclass
class Splits:
    train: tuple[int, int]
    val: tuple[int, int]
    test: tuple[int, int]

    def describe(self, ds: TrafficDataset) -> dict:
        def rng(a, b):
            return {"start_step": a, "end_step": b, "start": ds.timestamp(a).isoformat(), "end": ds.timestamp(b - 1).isoformat(), "steps": b - a}

        return {"train": rng(*self.train), "val": rng(*self.val), "test": rng(*self.test), "order": "chronological"}


def chronological_splits(num_steps: int, train_frac: float, val_frac: float) -> Splits:
    a = int(num_steps * train_frac)
    b = int(num_steps * (train_frac + val_frac))
    return Splits(train=(0, a), val=(a, b), test=(b, num_steps))


# --------------------------------------------------------------------------- windowing


class SensorSeries:
    """Target series for a set of sensors, normalised per sensor with training-period statistics only."""

    def __init__(self, ds: TrafficDataset, target: str, sensors: list[int], splits: Splits):
        self.ds = ds
        self.sensors = list(sensors)
        self.splits = splits
        raw = ds.values[:, sensors, ds.feature_index(target)].astype(np.float32)  # (T, n)
        self.raw = raw
        tr0, tr1 = splits.train
        train_vals = raw[tr0:tr1]
        # Zeros are treated as missing readings (standard PeMS/METR-LA practice) for statistics and metrics.
        masked = np.where(train_vals > 0, train_vals, np.nan)
        mean = np.nanmean(masked, axis=0)
        std = np.nanstd(masked, axis=0)
        self.mean = np.nan_to_num(mean, nan=0.0).astype(np.float32)
        self.std = np.where(np.nan_to_num(std, nan=0.0) < 1e-3, 1.0, np.nan_to_num(std, nan=1.0)).astype(np.float32)
        self.norm = ((raw - self.mean) / self.std).astype(np.float32)
        steps_per_day = 24 * 60 // ds.spec.interval_minutes
        t = np.arange(ds.num_steps)
        phase = 2 * np.pi * (t % steps_per_day) / steps_per_day
        dow = (t // steps_per_day + ds.spec.start_time.weekday()) % 7
        self.time_feats = np.stack([np.sin(phase), np.cos(phase), (dow >= 5).astype(np.float32)], axis=1).astype(np.float32)

    @property
    def num_input_features(self) -> int:
        return 1 + self.time_feats.shape[1]


@dataclass
class WindowSet:
    series: SensorSeries
    local_sensor_idx: np.ndarray  # column index into series arrays
    start_idx: np.ndarray  # window start step
    input_len: int
    horizon: int

    def __len__(self) -> int:
        return int(self.start_idx.shape[0])

    def batch(self, rows: np.ndarray):
        s = self.local_sensor_idx[rows][:, None]
        t0 = self.start_idx[rows][:, None]
        tin = t0 + np.arange(self.input_len)[None, :]
        tout = t0 + self.input_len + np.arange(self.horizon)[None, :]
        x_target = self.series.norm[tin, s][..., None]
        x_time = self.series.time_feats[tin]
        x = np.concatenate([x_target, x_time], axis=-1)
        y = self.series.norm[tout, s]
        y_raw = self.series.raw[tout, s]
        mean = self.series.mean[s[:, 0]][:, None]
        std = self.series.std[s[:, 0]][:, None]
        return x, y, y_raw, mean, std, t0[:, 0] + self.input_len


def make_windows(series: SensorSeries, columns: list[int], split: tuple[int, int], input_len: int, horizon: int, stride: int = 1) -> WindowSet:
    a, b = split
    starts = np.arange(a, b - input_len - horizon + 1, stride)
    cols = np.asarray(columns, dtype=np.int64)
    s_idx = np.repeat(cols, len(starts))
    t_idx = np.tile(starts, len(cols))
    return WindowSet(series, s_idx, t_idx, input_len, horizon)


def raw_record_bytes(ds: TrafficDataset, sensors: list[int], split: tuple[int, int]) -> int:
    """Size of the raw training records (all dataset features, float32) for the given sensors."""
    a, b = split
    return int(np.ascontiguousarray(ds.values[a:b, sensors, :], dtype=np.float32).nbytes)
